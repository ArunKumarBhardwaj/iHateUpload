/** Scores every converted .docx in results/ against the fixtures' truth and writes scoreboard.md and scoreboard.json. */
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

import { scoreDocx, type ScoreResult } from "./score";
import type { Truth } from "./types";

const HERE = import.meta.dirname;
const SIDES = ["ours", "rival", "rival-exact"] as const;
type Side = (typeof SIDES)[number];
const LABEL: Record<Side, string> = { ours: "Ours (Editable)", rival: "ihatepdf.cv (Editable)", "rival-exact": "ihatepdf.cv (Exact)" };
const FEATURE_LABEL: Record<string, string> = {
  text: "Text accuracy (1-CER)",
  order: "Reading order",
  editability: "Editability (not in text boxes)",
  paragraphs: "Paragraph breaks",
  headings: "Headings",
  lists: "Lists",
  tables: "Tables",
  runs: "Run formatting",
  images: "Images",
  vectors: "Vector shapes",
  links: "Links",
  columns: "Columns (w:cols)",
  fonts: "Fonts (names + embedded)",
  headerFooter: "Header / footer",
  footnotes: "Footnotes",
  forms: "Form fields",
};

type Rec = { times: number[]; hashes: string[]; errors: string[]; failures: number };
const median = (xs: number[]) => {
  const s = [...xs].sort((a, b) => a - b);
  return s.length ? (s.length % 2 ? s[(s.length - 1) / 2] : (s[s.length / 2 - 1] + s[s.length / 2]) / 2) : NaN;
};
const mean = (xs: number[]) => (xs.length ? xs.reduce((a, b) => a + b, 0) / xs.length : NaN);
const f2 = (n: number | undefined) => (n === undefined || Number.isNaN(n) ? "-" : n.toFixed(2));
const sec = (ms: number) => (Number.isNaN(ms) ? "-" : (ms / 1000).toFixed(2) + " s");

const fixtures = readdirSync(join(HERE, "fixtures")).filter((f) => f.endsWith(".truth.json")).map((f) => f.replace(".truth.json", "")).sort();
const truths: Record<string, Truth> = {};
for (const f of fixtures) truths[f] = JSON.parse(readFileSync(join(HERE, "fixtures", f + ".truth.json"), "utf8"));

type Cell = { score?: ScoreResult; rec?: Rec; failed: boolean };
const data: Record<string, Record<Side, Cell>> = {};
for (const f of fixtures) {
  data[f] = {} as Record<Side, Cell>;
  for (const s of SIDES) {
    const docx = join(HERE, "results", s, f + ".docx");
    const recPath = join(HERE, "results", s, f + ".json");
    const rec: Rec | undefined = existsSync(recPath) ? JSON.parse(readFileSync(recPath, "utf8")) : undefined;
    if (!existsSync(docx)) {
      data[f][s] = { rec, failed: !!rec };
      continue;
    }
    // A failed conversion scores 0 on every feature the fixture has; scoring a docx that parses badly does the same.
    try {
      data[f][s] = { score: await scoreDocx(readFileSync(docx), truths[f]), rec, failed: false };
    } catch (e) {
      console.error("score failed", f, s, e);
      data[f][s] = { rec, failed: true };
    }
  }
}

function zeroScore(t: Truth, probe: ScoreResult | undefined): ScoreResult {
  const features: Record<string, number> = {};
  for (const k of Object.keys(probe?.features ?? {})) features[k] = 0;
  void t;
  return { features, detail: {}, overall: 0 };
}
// Feature set per fixture comes from any side that scored; a failed side gets zeros.
for (const f of fixtures) {
  const probe = SIDES.map((s) => data[f][s].score).find(Boolean);
  for (const s of SIDES) if (data[f][s].failed && !data[f][s].score && probe) data[f][s].score = zeroScore(truths[f], probe);
}

const featureKeys = Object.keys(FEATURE_LABEL);
const agg: Record<Side, Record<string, number>> = { ours: {}, rival: {}, "rival-exact": {} };
const overall: Record<Side, number> = { ours: NaN, rival: NaN, "rival-exact": NaN };
for (const s of SIDES) {
  for (const k of featureKeys) {
    const xs = fixtures.map((f) => data[f][s].score?.features[k]).filter((x): x is number => x !== undefined);
    if (xs.length) agg[s][k] = mean(xs);
  }
  overall[s] = mean(fixtures.map((f) => data[f][s].score?.overall).filter((x): x is number => x !== undefined));
}

const timeStats = (f: string, s: Side) => {
  const t = data[f][s].rec?.times ?? [];
  return { n: t.length, med: median(t), min: Math.min(...t), max: Math.max(...t) };
};

// ---- markdown ----
const L: string[] = [];
L.push("# PDF to Word scoreboard: ours vs ihatepdf.cv", "");
const runsNote = fixtures.map((f) => `${f}:${timeStats(f, "ours").n}`).join(", ");
L.push(`Generated by \`bun run bench:pdf2word\`. ${fixtures.length} synthetic fixtures; ground truth is written by \`fixtures/gen.ts\`. Scores are 0 to 1 (higher is better). Both sides ran with every option on (ihatepdf.cv: embed fonts, images, tables, headers/footers, columns, drawings, OCR); ours in Editable text mode. Timing runs per fixture (ours): ${runsNote}.`, "");
L.push("## Features (mean over fixtures that contain the feature)", "");
L.push(`| Feature | ${SIDES.map((s) => LABEL[s]).join(" | ")} | Gap (theirs - ours) |`, `|---|${SIDES.map(() => "---:").join("|")}|---:|`);
for (const k of featureKeys) {
  if (agg.ours[k] === undefined && agg.rival[k] === undefined) continue;
  const gap = (agg.rival[k] ?? NaN) - (agg.ours[k] ?? NaN);
  L.push(`| ${FEATURE_LABEL[k]} | ${SIDES.map((s) => f2(agg[s][k])).join(" | ")} | ${Number.isNaN(gap) ? "-" : (gap > 0 ? "+" : "") + gap.toFixed(2)} |`);
}
L.push(`| **Overall (mean of fixture overalls)** | ${SIDES.map((s) => `**${f2(overall[s])}**`).join(" | ")} | ${(overall.rival - overall.ours > 0 ? "+" : "") + (overall.rival - overall.ours).toFixed(2)} |`);
const allMed = (s: Side) => median(fixtures.filter((f) => f !== "long").map((f) => timeStats(f, s).med).filter((x) => !Number.isNaN(x)));
L.push(`| Median conversion time (small fixtures) | ${sec(allMed("ours"))} | ${sec(allMed("rival"))} | ${sec(allMed("rival-exact"))} | |`);
if (fixtures.includes("long")) L.push(`| Conversion time, ${truths.long?.pages ?? "120"}-page file (median) | ${sec(timeStats("long", "ours").med)} | ${sec(timeStats("long", "rival").med)} | ${sec(timeStats("long", "rival-exact").med)} | |`);
L.push("");

L.push("## Gaps, biggest first (feature, ihatepdf.cv score minus ours; positive means they are ahead)", "");
const gaps: { f: string; k: string; ours: number; theirs: number; gap: number }[] = [];
for (const f of fixtures) {
  const o = data[f].ours.score;
  const r = data[f].rival.score;
  if (!o || !r) continue;
  for (const k of Object.keys(o.features)) gaps.push({ f, k, ours: o.features[k], theirs: r.features[k] ?? 0, gap: (r.features[k] ?? 0) - o.features[k] });
}
gaps.sort((a, b) => b.gap - a.gap);
L.push("| Fixture | Feature | Ours | ihatepdf.cv | Gap |", "|---|---|---:|---:|---:|");
for (const g of gaps.filter((x) => Math.abs(x.gap) >= 0.05)) L.push(`| ${g.f} | ${FEATURE_LABEL[g.k]} | ${f2(g.ours)} | ${f2(g.theirs)} | ${g.gap > 0 ? "+" : ""}${g.gap.toFixed(2)} |`);
L.push("", "Features where we are ahead appear at the bottom with a negative gap.", "");

L.push("## Per fixture", "");
L.push("| Fixture | Pages | Ours overall | ihatepdf.cv overall | Ours time median (range, n) | ihatepdf.cv time median (range, n) | Same output every run? ours / theirs |", "|---|---:|---:|---:|---|---|---|");
const rep = (f: string, s: Side) => {
  const h = data[f][s].rec?.hashes ?? [];
  return h.length ? (new Set(h).size === 1 ? "yes" : `NO (${new Set(h).size} variants)`) : "-";
};
const tfmt = (f: string, s: Side) => {
  const t = timeStats(f, s);
  return t.n ? `${sec(t.med)} (${sec(t.min)} to ${sec(t.max)}, n=${t.n})` : "-";
};
for (const f of fixtures) L.push(`| ${f} | ${truths[f].pages} | ${f2(data[f].ours.score?.overall)} | ${f2(data[f].rival.score?.overall)} | ${tfmt(f, "ours")} | ${tfmt(f, "rival")} | ${rep(f, "ours")} / ${rep(f, "rival")} |`);
L.push("");
L.push("### Feature scores per fixture (ours / ihatepdf.cv / ihatepdf.cv Exact)", "");
L.push(`| Fixture | ${featureKeys.map((k) => FEATURE_LABEL[k]).join(" | ")} |`, `|---|${featureKeys.map(() => "---").join("|")}|`);
for (const f of fixtures) {
  const cells = featureKeys.map((k) => {
    const v = SIDES.map((s) => data[f][s].score?.features[k]);
    return v.every((x) => x === undefined) ? "" : v.map(f2).join(" / ");
  });
  L.push(`| ${f} | ${cells.join(" | ")} |`);
}
L.push("");
const fails = fixtures.flatMap((f) => SIDES.filter((s) => data[f][s].rec?.failures).map((s) => `${f}/${s}: ${data[f][s].rec!.failures} failed run(s), ${data[f][s].rec!.errors.slice(-1)[0] ?? ""}`));
L.push("## Failures and page errors", "", fails.length ? fails.map((x) => "- " + x).join("\n") : "None: every run produced a downloadable .docx.", "");
L.push(
  "## How to read this",
  "",
  "- Scores come from the generator's truth JSON, never from either converter. Each feature is scored only on fixtures whose truth contains it, so a feature that appears in one fixture rests on that one fixture.",
  "- Text accuracy is 1 minus the character error rate over alphabetically sorted words, so it ignores order (reading order is scored separately by word-sequence LCS divided by shared words). Over about 9,000 characters (the 120-page file) it falls back to a character-weighted word F1. Chrome-printed fixtures use clean ASCII text, so text scores sit at the ceiling and do not separate the sides.",
  "- Lists give 1 for a real Word list item of the right type, 0.25 for an item that is its own paragraph without a real list, 0 when merged into another paragraph. Run formatting is one micro F1 over bold, italic, underline, strike, sup, sub, highlight, colour and size departures from black and 12 pt. Vector shapes count shapes plus pictures against the drawn count. Fonts are half name match, half any embedded font file. Tables take the mean of cell-grid exact match, merge F1 and shading F1, with a split-table penalty.",
  "- Not scored: bookmarks/outline, real Word footnote numbering, table borders, image resolution, visual fidelity in Word itself (nothing here opens Word or LibreOffice).",
  "- Time runs from the file being chosen to the download being ready, in one headless Chrome, sides alternating per run. Resolution is roughly 0.1 s (Playwright polling), so differences under that are noise. Ours runs against the production build (`next start`); ihatepdf.cv runs as deployed over the internet. The 120-page file runs 3 times per side, the rest 5. The ihatepdf.cv Exact column is one run per fixture, scored only.",
  "",
);
writeFileSync(join(HERE, "scoreboard.md"), L.join("\n"));
writeFileSync(
  join(HERE, "scoreboard.json"),
  JSON.stringify({ sides: SIDES, features: agg, overall, perFixture: Object.fromEntries(fixtures.map((f) => [f, Object.fromEntries(SIDES.map((s) => [s, { overall: data[f][s].score?.overall ?? null, features: data[f][s].score?.features ?? null, detail: data[f][s].score?.detail ?? null, time: timeStats(f, s), hashes: data[f][s].rec?.hashes ?? [] }]))])), gaps }, (k, v) => (typeof v === "number" && !Number.isFinite(v) ? null : v), 1) + "\n",
);
console.log(L.slice(0, 40).join("\n"));
